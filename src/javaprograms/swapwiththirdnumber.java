package javaprograms;

public class swapwiththirdnumber {

	public static void main(String[] args) {

		int a=20;
		int b=30;
		int temp=0;
		
		System.out.println("before swapping:"+a);
		System.out.println("before swapping:"+b);

		
		
		
		temp=a;
		a=b;
		b=temp;
		
		System.out.println("before swapping:"+a);
		System.out.println("before swapping:"+b);

		
		
		
	}

}
